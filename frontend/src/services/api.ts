import axios from 'axios'

/**
 * Same-origin API base. In development Vite proxies `/api` and `/uploads` to
 * Spring Boot (see vite.config.ts); in a production build the frontend is served
 * from the same origin as the API. Using a relative base avoids CORS entirely
 * and keeps the app working behind any host name or port.
 */
const API_BASE_URL = '/api'

export const api = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
})

// Request interceptor to add JWT token
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('token')
    if (token) {
      config.headers.Authorization = `Bearer ${token}`
    }
    return config
  },
  (error) => {
    return Promise.reject(error)
  }
)

// Response interceptor to handle errors
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401) {
      localStorage.removeItem('token')
      window.location.href = '/login'
    }
    return Promise.reject(error)
  }
)